# Aspas simples ou compostas.
nome = "Gustavo L"
curso = 'ADS'

# Concatenar texto no print!
print("Meu nome é " + nome, " e eu curso " + curso)

# f-string, dentro do texto use {} para variaveis
print(f"Meu nome é {nome}\nEu curso {curso}")

# Quebra de linha \n
# Aspas dentro do texto = Dentro de ' "" '

print('Nome: '+ nome + ' "Curso: "' + curso)

# Tabulação = Espaço do TAB
print("Nome: \t Gustavo\t Sou")