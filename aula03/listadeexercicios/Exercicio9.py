print("--------Conversor de horas para minutos e segundos-----------------")

horas = float(input("Digite a quantidade de horas para ser convertida: "))
print("----------------------------------------------\n")

minutos = horas * 60
print(horas, " Horas são:  ", minutos, " Minutos\n")

segundos = minutos * 60
print(horas, " Horas são:", segundos, " Segundos")